const patterns = [
  [/^Final lap: blue beacon (\d+) of (\d+)\. Sprint to beat the clock\.$/, (_, n, total) => `最后一圈：第 ${n} / ${total} 个蓝色信标。冲刺赶在时间结束前完成。`],
  [/^(\d+) students? (?:is|are) chasing$/, (_, n) => `${n} 名学生正在追赶`],
  [/^Kick · ([\d.]+)s$/, (_, n) => `踢击冷却 · ${n} 秒`],
  [/^Bell returns in (\d+)s$/, (_, n) => `诱饵铃将在 ${n} 秒后就绪`],
  [/^Checkpoint (\d+) \/ (\d+)\. Follow the next blue beacon\.$/, (_, n, total) => `检查点 ${n} / ${total}。前往下一个蓝色信标。`],
  [/^Track beacon (\d+) \/ (\d+)$/, (_, n, total) => `跑道信标 ${n} / ${total}`],
  [/^TRACK · (\d+) \/ (\d+)$/, (_, n, total) => `跑道 · ${n} / ${total}`],
  [/^(\d+) memories are still waiting\. M shows the campus routes\.$/, (_, n) => `还有 ${n} 份记忆等待找回。M 查看校园路线。`],
  [/^Reach the blue track beacons in order\. (\d+) seconds remain\.$/, (_, n) => `依次到达蓝色跑道信标。剩余 ${n} 秒。`],
  [/^The room sings: (I|II|III)$/, (_, note) => `房间奏响：${note}`],
  [/^(.+) — remembered\. (?:(\d+) remain\.|Return to the plaza gate\.)$/, (_, title, n) => `${translations[title] || title}——已找回。${n ? `还剩 ${n} 份。` : '返回广场大门。'}`],
  [/^(.+) · (\d+) units$/, (_, label, n) => `${chinese(label) || label} · 距离 ${n} 单位`]
];
function chinese(value) {
  if (Object.hasOwn(translations, value)) return translations[value];
  for (const [pattern, format] of patterns) {
    const match = value.match(pattern);
    if (match) return format(...match);
  }
}
export function bilingual(value) {
  const english = String(value ?? '');
  const translation = chinese(english);
  return translation ? `${english} / ${translation}` : english;
}
// Translate text nodes without replacing elements, IDs, buttons or event listeners.
export function translateNight(document) {
  if (document.body?.dataset.campusMode !== 'night') return;
  const walker = document.createTreeWalker(document.body, 4);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest('script,style')) continue;
    const raw = node.nodeValue;
    const trimmed = raw.trim();
    if (trimmed) node.nodeValue = raw.replace(trimmed, bilingual(trimmed));
  }
  for (const element of document.querySelectorAll('[aria-label],[title]')) {
    for (const attribute of ['aria-label', 'title']) {
      if (element.hasAttribute(attribute)) element.setAttribute(attribute, bilingual(element.getAttribute(attribute)));
    }
  }
}
